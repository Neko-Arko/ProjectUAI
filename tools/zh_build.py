#!/usr/bin/env python3
"""Port of tools/bundle.lua.

The upstream bundler needs LuaJIT, which is not present on this machine. This
port reproduces its output byte for byte so a localized build can be produced
without the Lua toolchain. Verify with --check against a committed dist.

    python tools/zh_build.py --check     # compare with existing dist/
    python tools/zh_build.py             # write dist/uai.lua + manifest
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WS = " \t\n\r\f\v"


def normalize(data: bytes) -> bytes:
    return data.replace(b"\r\n", b"\n").rstrip(WS.encode())


def dual32(version: str, modules, bootstrap: bytes) -> str:
    first, second = 5381, 2166136261

    def add(value):
        nonlocal first, second
        if isinstance(value, str):
            value = value.encode()
        value = normalize(value)
        for byte in value:
            first = (first * 33 + byte) % 4294967291
            second = (second * 65599 + byte) % 4294967279
        first = (first * 33) % 4294967291
        second = (second * 65599) % 4294967279

    add(version)
    for module in modules:
        add(module["id"])
        add(module["source"])
    add(bootstrap)
    return "%s-%08x%08x" % (version, first, second)


class Emitter:
    def __init__(self):
        self.lines = []
        self.next_line = 1

    def emit(self, line):
        if isinstance(line, str):
            line = line.encode()
        self.lines.append(line)
        start = self.next_line
        self.next_line += line.count(b"\n") + 1
        return start, self.next_line - 1


def collect_modules():
    modules = []
    for path in sorted((ROOT / "src").rglob("*.lua")):
        rel = path.relative_to(ROOT / "src").as_posix()
        module_id = rel[: -len(".lua")]
        source = normalize(path.read_bytes())
        modules.append({"id": module_id, "source": source, "bytes": len(source)})
    return modules


def build():
    modules = collect_modules()
    if not modules:
        raise SystemExit("no modules found under src/")
    boot = normalize((ROOT / "init.lua").read_bytes())
    match = re.search(rb'local VERSION = "([^"]+)"', boot)
    if not match:
        raise SystemExit('init.lua must declare local VERSION = "<version>"')
    version = match.group(1).decode()

    build_id = dual32(version, modules, boot)
    for module in modules:
        module["hash"] = dual32("module", [module], b"")

    total = sum(module["bytes"] for module in modules)
    out = Emitter()
    out.emit("-- Project UAI " + version + " -- a universal Roblox AI agent client.")
    out.emit("-- Build " + build_id)
    out.emit("--")
    out.emit("-- Generated by tools/bundle.lua. Do not edit: change src/ and rebuild.")
    out.emit("-- %d modules, %d bytes of source." % (len(modules), total))
    out.emit("--")
    out.emit("-- Usage:")
    out.emit('--     loadstring(game:HttpGet("<url>/dist/uai.lua"))()')
    out.emit("--")
    for module in modules:
        out.emit("--   %-28s %6d bytes  %s" % (module["id"], module["bytes"], module["hash"]))
    out.emit("")
    out.emit('local __UAI_BUILD = "%s"' % build_id)
    out.emit("local __UAI_MODULES = {}")
    out.emit("")

    # The committed artifact uses a space after the comment leader; the current
    # upstream bundle.lua no longer does. Matching the artifact keeps the
    # localization diff limited to translated strings.
    separator = "-- " + "=" * 74
    for module in modules:
        out.emit(separator)
        out.emit("-- " + module["id"])
        out.emit(separator)
        out.emit('__UAI_MODULES["%s"] = (function()' % module["id"])
        start, end = out.emit(module["source"])
        module["sourceStartLine"], module["sourceEndLine"] = start, end
        out.emit("end)()")
        out.emit("")

    out.emit(separator)
    out.emit("-- bootstrap")
    out.emit(separator)
    boot_start, boot_end = out.emit(boot)
    out.emit("")

    bundle = b"\n".join(out.lines)

    head = (
        '{"format":"uai-build","version":1,"hashAlgorithm":"uai-dual32-v1",'
        '"buildId":"%s","bootstrapHash":"%s",' % (build_id, dual32("init", [], boot))
    )
    body = '"bootstrap":{"sourceStartLine":%d,"sourceEndLine":%d},"modules":[' % (
        boot_start,
        boot_end,
    )
    entries = [
        '{"id":"%s","bytes":%d,"hash":"%s","sourceStartLine":%d,"sourceEndLine":%d}'
        % (
            module["id"],
            module["bytes"],
            module["hash"],
            module["sourceStartLine"],
            module["sourceEndLine"],
        )
        for module in modules
    ]
    manifest = (head + body + ",".join(entries) + "]}\n").encode()
    return bundle, manifest, build_id


def main():
    bundle, manifest, build_id = build()
    if "--check" in sys.argv:
        ok = True
        for name, produced in (("dist/uai.lua", bundle), ("dist/uai.manifest.json", manifest)):
            # The working tree checks out CRLF on Windows; compare normalized.
            current = (ROOT / name).read_bytes().replace(b"\r\n", b"\n")
            if current != produced:
                ok = False
                print("MISMATCH %s (committed %d bytes, produced %d bytes)"
                      % (name, len(current), len(produced)))
        print(("byte-identical: " if ok else "differs: ") + build_id)
        return 0 if ok else 1

    (ROOT / "dist").mkdir(exist_ok=True)
    (ROOT / "dist" / "uai.lua").write_bytes(bundle)
    (ROOT / "dist" / "uai.manifest.json").write_bytes(manifest)
    print("dist/uai.lua written: %d modules, %d bytes (%s)"
          % (bundle.count(b'__UAI_MODULES["'), len(bundle), build_id))
    return 0


if __name__ == "__main__":
    sys.exit(main())
