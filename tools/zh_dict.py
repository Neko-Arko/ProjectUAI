#!/usr/bin/env python3
"""Generate src/runtime/locale_zh.lua from l10n/zh.json.

The JSON file is the single source of truth: it is what a translator edits, what
a diff review reads, and what survives an upstream merge. The Lua module is a
build artifact kept in the tree only because the bundler concatenates src/.

    python tools/zh_dict.py            # write src/runtime/locale_zh.lua
    python tools/zh_dict.py --check    # fail if the module is stale
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "l10n" / "zh.json"
TARGET = ROOT / "src" / "runtime" / "locale_zh.lua"

HEADER = """-- Generated by tools/zh_dict.py from l10n/zh.json -- do not edit by hand.
--
-- Simplified Chinese interface strings. Keys are the exact English source text;
-- values are what the user reads. %{name} marks a value the code fills in.
return function(env)
	return {
"""

FOOTER = """	}
end
"""


def lua_string(text: str) -> str:
    out = []
    for char in text:
        if char == "\\":
            out.append("\\\\")
        elif char == '"':
            out.append('\\"')
        elif char == "\n":
            out.append("\\n")
        elif char == "\r":
            out.append("\\r")
        elif char == "\t":
            out.append("\\t")
        else:
            out.append(char)
    return '"' + "".join(out) + '"'


def load():
    entries = {}
    files = [SOURCE] + sorted((ROOT / "l10n" / "parts").glob("*.json"))
    for path in files:
        if not path.exists():
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        part = data["entries"] if isinstance(data, dict) and "entries" in data else data
        for source, target in part.items():
            if not isinstance(source, str) or not isinstance(target, str):
                raise SystemExit("bad entry in %s: %r -> %r" % (path.name, source, target))
            if not source:
                continue
            # A duplicate key with two different translations is a mistake, not an
            # override: the reader would get whichever file sorted last.
            if source in entries and entries[source] != target:
                raise SystemExit("conflicting translation for %r in %s" % (source, path.name))
            entries[source] = target
    return entries


def render(entries) -> str:
    lines = [HEADER]
    current = None
    for source in sorted(entries):
        initial = source[:1].lower()
        if initial != current:
            current = initial
            lines.append("\t\t-- %s\n" % current)
        lines.append("\t\t[%s] = %s,\n" % (lua_string(source), lua_string(entries[source])))
    lines.append(FOOTER)
    return "".join(lines)


def main():
    entries = load()
    body = render(entries)
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != body:
            print("locale_zh.lua is stale; run python tools/zh_dict.py")
            return 1
        print("locale_zh.lua current: %d entries" % len(entries))
        return 0
    TARGET.write_text(body, encoding="utf-8")
    print("locale_zh.lua written: %d entries, %d bytes" % (len(entries), len(body.encode())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
