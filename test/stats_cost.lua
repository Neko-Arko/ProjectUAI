package.path = "test/?.lua;test/mock/?.lua;" .. package.path
local F = require("workspace_fixture")
local suite = F.suite("Historical cost coverage")
local check = suite.check
suite.case("unknown-cost and cache-write history survives reload", function()
	local f = F.new(); local stats = f.env.require("agent/stats")
	stats.recordRequest({ model = "fixture", prompt = 100, completion = 20, cost = 0, costKnown = false, cacheCreated = 12 })
	stats.recordRequest({ model = "fixture", prompt = 50, completion = 10, cost = 0, costKnown = true })
	local window = stats.window("all")
	check("unknown request is recorded separately", window.unpriced == 1 and window.models[1].unpriced == 1 and window.requests == 2)
	check("zero-cost known request does not become unknown", stats.data.totals.unpriced == 1)
	check("cache writes reach lifetime totals", stats.data.totals.cacheCreated == 12)
	check("history is persisted", stats.saveNow())
	stats.load(); window = stats.window("all")
	check("unknown counts survive a fresh load", window.unpriced == 1 and window.models[1].unpriced == 1 and stats.data.models.fixture.unpriced == 1)
	check("cache-write total survives a fresh load", stats.data.totals.cacheCreated == 12)
	stats.reset(); check("reset clears coverage", stats.window("all").unpriced == 0)
	f.healthy(); f.close()
end)
suite.finish()
